class BundleProduct {
  final String id;
  final String name;
  final double price;
  final double weight;
  final int quantity;
  final String imageUrl;

  BundleProduct({
    required this.id,
    required this.name,
    required this.price,
    required this.weight,
    required this.quantity,
    required this.imageUrl,
  });
}
